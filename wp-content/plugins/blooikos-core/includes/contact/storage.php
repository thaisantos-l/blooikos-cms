<?php
/**
 * Bounded, shared contact quotas and metadata-only diagnostics.
 *
 * @package BlooikosCore
 */

// Custom atomic storage cannot use the object cache. Identifiers use wpdb %i.
// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching

/**
 * Idempotent install for activation and the first valid POST after an upgrade.
 * No schema writes occur on ordinary page reads, GET or OPTIONS.
 *
 * @return bool
 */
function blooikos_core_contact_install() {
	global $wpdb;
	$previous = $wpdb->suppress_errors( true );
	$charset  = $wpdb->get_charset_collate();
	// Charset/collation is generated by WordPress, never supplied by the request.
	$quota  = $wpdb->query( $wpdb->prepare( 'CREATE TABLE IF NOT EXISTS %i (bucket varchar(66) NOT NULL, attempts int unsigned NOT NULL, expires bigint unsigned NOT NULL, PRIMARY KEY (bucket), KEY expires (expires)) ENGINE=InnoDB ', $wpdb->prefix . 'blooikos_contact_quota' ) . $charset ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.DirectDatabaseQuery.SchemaChange -- Idempotent own technical tables; prepared identifier and trusted charset.
	$events = $wpdb->query( $wpdb->prepare( 'CREATE TABLE IF NOT EXISTS %i (slot tinyint unsigned NOT NULL, request_id char(36) NOT NULL, code varchar(32) NOT NULL, duration_ms int unsigned NOT NULL, occurred bigint unsigned NOT NULL, PRIMARY KEY (slot)) ENGINE=InnoDB ', $wpdb->prefix . 'blooikos_contact_events' ) . $charset ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.DirectDatabaseQuery.SchemaChange -- Idempotent own technical tables; prepared identifier and trusted charset.
	$wpdb->suppress_errors( $previous );
	return false !== $quota && false !== $events;
}

/**
 * Reserve both windows under one database advisory lock and transaction.
 *
 * @return array Code, or retryAfter when a window is exhausted.
 */
function blooikos_core_contact_reserve() {
	global $wpdb;
	// Only the connection address is trusted; no forwarded headers are consumed.
	$address = isset( $_SERVER['REMOTE_ADDR'] ) ? filter_var( wp_unslash( $_SERVER['REMOTE_ADDR'] ), FILTER_VALIDATE_IP ) : false;
	if ( ! $address ) {
		return array( 'code' => 'CONTACT_UNAVAILABLE' );
	}
	$client   = 'c:' . hash_hmac( 'sha256', inet_ntop( inet_pton( $address ) ), wp_salt( 'auth' ) );
	$table    = $wpdb->prefix . 'blooikos_contact_quota';
	$lock     = 'blooikos-contact-' . substr( hash( 'sha256', DB_NAME . ':' . $table ), 0, 40 );
	$previous = $wpdb->suppress_errors( true );
	$held     = false;
	$active   = false;
	try {
		$held = '1' === (string) $wpdb->get_var( $wpdb->prepare( 'SELECT GET_LOCK(%s, 2)', $lock ) );
		if ( ! $held || ! blooikos_core_contact_install() || false === $wpdb->query( 'START TRANSACTION' ) ) {
			return array( 'code' => 'CONTACT_UNAVAILABLE' );
		}
		$active = true;
		$now    = time();
		if ( false === $wpdb->query( $wpdb->prepare( 'DELETE FROM %i WHERE expires <= %d LIMIT 100', $table, $now ) ) ) {
			return array( 'code' => 'CONTACT_UNAVAILABLE' );
		}
		$count = $wpdb->get_var( $wpdb->prepare( 'SELECT COUNT(*) FROM %i', $table ) );
		if ( null === $count || (int) $count >= 2046 ) {
			return array( 'code' => 'CONTACT_UNAVAILABLE' );
		}
		$windows = array(
			'global' => array( 60, HOUR_IN_SECONDS ),
			$client  => array( 5, 15 * MINUTE_IN_SECONDS ),
		);
		$rows    = array();
		$retry   = 0;
		foreach ( $windows as $bucket => $rule ) {
			$row = $wpdb->get_row( $wpdb->prepare( 'SELECT attempts, expires FROM %i WHERE bucket = %s FOR UPDATE', $table, $bucket ), ARRAY_A );
			if ( $wpdb->last_error ) {
				return array( 'code' => 'CONTACT_UNAVAILABLE' );
			}
			if ( ! $row || (int) $row['expires'] <= $now ) {
				$row = array(
					'attempts' => 0,
					'expires'  => $now + $rule[1],
				);
			}
			if ( (int) $row['attempts'] >= $rule[0] ) {
				$retry = max( $retry, (int) $row['expires'] - $now );
			}
			$rows[ $bucket ] = $row;
		}
		if ( $retry ) {
			return array(
				'code'       => 'RATE_LIMITED',
				'retryAfter' => $retry,
			);
		}
		foreach ( $rows as $bucket => $row ) {
			if ( false === $wpdb->replace(
				$table,
				array(
					'bucket'   => $bucket,
					'attempts' => (int) $row['attempts'] + 1,
					'expires'  => (int) $row['expires'],
				),
				array( '%s', '%d', '%d' )
			) ) {
				return array( 'code' => 'CONTACT_UNAVAILABLE' );
			}
		}
		if ( false === $wpdb->query( 'COMMIT' ) ) {
			return array( 'code' => 'CONTACT_UNAVAILABLE' );
		}
		$active = false;
		return array();
	} finally {
		if ( $active ) {
			$wpdb->query( 'ROLLBACK' );
		}
		if ( $held ) {
			$wpdb->get_var( $wpdb->prepare( 'SELECT RELEASE_LOCK(%s)', $lock ) );
		}
		$wpdb->suppress_errors( $previous );
	}
}

/**
 * Bounded diagnostics, without body, headers, addresses or visitor identifiers.
 * Up to 64 slots, expiring after 24 hours; cleanup on the next logged POST.
 * Schema/storage failure cannot leak database error details into PHP logs.
 *
 * @param string $request_id Server UUID.
 * @param string $code Result code.
 * @param int    $duration Duration in milliseconds.
 * @return void
 */
function blooikos_core_contact_record( $request_id, $code, $duration ) {
	global $wpdb;
	$previous = $wpdb->suppress_errors( true );
	$table    = $wpdb->prefix . 'blooikos_contact_events';
	$wpdb->query( $wpdb->prepare( 'DELETE FROM %i WHERE occurred <= %d LIMIT 64', $table, time() - DAY_IN_SECONDS ) );
	$wpdb->replace(
		$table,
		array(
			'slot'        => hexdec( substr( hash( 'sha256', $request_id ), 0, 4 ) ) % 64,
			'request_id'  => $request_id,
			'code'        => $code,
			'duration_ms' => $duration,
			'occurred'    => time(),
		),
		array( '%d', '%s', '%s', '%d', '%d' )
	);
	$wpdb->suppress_errors( $previous );
	/** Fires with non-personal operational metadata, even when storage is unavailable. */
	do_action( 'blooikos_core_contact_result', $request_id, $code, $duration, time() );
}
